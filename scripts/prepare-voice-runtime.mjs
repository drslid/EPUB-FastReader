import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const runtime = path.join(root, "public/voice-runtime/v1");
const sha256 = (data) => createHash("sha256").update(data).digest("hex");
const EPHONE_REVISION = "4f6d246c1d3acf67a4d814e20da02fa3967bc92d";
const EPHONE_SOURCE_HASH = "a2d68b463730754d7f3cdd598a77072631dcf9b343c38ffeee538a8ce082955e";

async function copy(source, target) {
  const destination = path.join(runtime, target);
  await mkdir(path.dirname(destination), { recursive: true });
  await copyFile(path.join(root, source), destination);
  const data = await readFile(destination);
  return { file: target, bytes: data.byteLength, sha256: sha256(data) };
}

async function correspondingSource() {
  const cached = path.join(root, ".cache/ephone-source-1.0.2.tar.gz");
  let source;
  try { source = await readFile(cached); } catch { /* First build. */ }
  if (!source || sha256(source) !== EPHONE_SOURCE_HASH) {
    const response = await fetch(`https://codeload.github.com/sjmik/ephone-js/tar.gz/${EPHONE_REVISION}`, {
      signal: AbortSignal.timeout(60_000),
    });
    if (!response.ok) throw new Error(`Unable to obtain ephone corresponding source: HTTP ${response.status}`);
    source = Buffer.from(await response.arrayBuffer());
    if (sha256(source) !== EPHONE_SOURCE_HASH) throw new Error("ephone corresponding source checksum mismatch");
    await mkdir(path.dirname(cached), { recursive: true });
    await writeFile(cached, source);
  }
  await mkdir(path.join(runtime, "licenses"), { recursive: true });
  await writeFile(path.join(runtime, "licenses/ephone-1.0.2-source.tar.gz"), source);
}

/** Copy optional browser runtimes, never download the Kokoro model at build. */
export async function prepareVoiceRuntime() {
  for (const [name, version] of [["@huggingface/transformers", "3.8.1"], ["ephone", "1.0.2"]]) {
    const installed = JSON.parse(await readFile(path.join(root, "node_modules", name, "package.json"), "utf8"));
    if (installed.version !== version) throw new Error(`Expected ${name}@${version}; run npm ci`);
  }
  const assets = [];
  for (const [source, target, pack] of [
    ["src/voice-worker.js", "worker.js"],
    ["node_modules/@huggingface/transformers/dist/transformers.min.js", "vendor/transformers.min.js"],
    ["node_modules/@huggingface/transformers/dist/ort-wasm-simd-threaded.jsep.mjs", "vendor/ort-wasm-simd-threaded.jsep.mjs"],
    ["node_modules/@huggingface/transformers/dist/ort-wasm-simd-threaded.jsep.wasm", "vendor/ort-wasm-simd-threaded.jsep.wasm"],
    ["node_modules/ephone/ephone.js", "vendor/ephone.js"],
    ["node_modules/ephone/lang/roa.js", "vendor/lang/roa.js", "roa"],
    ["node_modules/ephone/lang/en-us.js", "vendor/lang/en-us.js", "en_us"],
  ]) {
    const asset = await copy(source, target);
    assets.push(pack ? { ...asset, pack } : asset);
  }
  await correspondingSource();
  await copy("docs/licenses/GPL-3.0.txt", "licenses/GPL-3.0.txt");
  await copy("docs/licenses/Apache-2.0.txt", "licenses/Apache-2.0.txt");
  await copy("docs/licenses/ONNX-Runtime-MIT.txt", "licenses/ONNX-Runtime-MIT.txt");
  await copy("docs/THIRD-PARTY-VOICE.md", "licenses/THIRD-PARTY-VOICE.md");
  const manifest = `// Generated by scripts/prepare-voice-runtime.mjs. Do not edit.\nexport const RUNTIME_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
  const manifestPath = path.join(root, "src/voice-runtime-manifest.js");
  let current;
  try { current = await readFile(manifestPath, "utf8"); } catch { /* First build. */ }
  if (current !== manifest) await writeFile(manifestPath, manifest);
  return assets;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const assets = await prepareVoiceRuntime();
  console.log(`Prepared ${assets.length} optional speech assets; no model was downloaded.`);
}
